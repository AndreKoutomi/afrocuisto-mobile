    Font(R.font.nexa_bold, FontWeight.Bold),
    Font(R.font.nexa_bold, FontWeight.ExtraBold),
    Font(R.font.nexa_bold, FontWeight.Black)
)

/** Gives bold Nexa headings a pronounced ExtraBold/Black visual weight without changing the typeface. */
fun Modifier.nexaTitleEmphasis(): Modifier = drawWithContent {
    val offsetPx = 0.55.dp.toPx()
    drawContent()
    drawContext.transform.translate(left = offsetPx, top = 0f)
    drawContent()
    drawContext.transform.translate(left = -offsetPx, top = 0f)
}

