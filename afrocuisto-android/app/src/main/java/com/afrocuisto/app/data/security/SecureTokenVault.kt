package com.afrocuisto.app.data.security

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.nio.charset.StandardCharsets
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Hardware-backed Android Keystore AES-256-GCM vault for encrypting sensitive session tokens
 * (`access_token` & `refresh_token`) at rest before storing in DataStore.
 *
 * - Keys are generated inside TEE / StrongBox (`AndroidKeyStore`) and never leave secure hardware.
 * - Uses randomized 96-bit IVs generated by Keystore + 128-bit GCM authentication tag.
 * - Any tampering or key invalidation safely returns empty string so the session is wiped cleanly.
 */
object SecureTokenVault {
    private const val ANDROID_KEYSTORE = "AndroidKeyStore"
    private const val KEY_ALIAS = "afrocuisto_auth_aes256_gcm_v1"
    private const val TRANSFORMATION = "AES/GCM/NoPadding"
    private const val GCM_TAG_BITS = 128
    private const val VERSION_PREFIX = "v1:"

    @Synchronized
    private fun getOrCreateSecretKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        val existing = keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry
        if (existing != null) return existing.secretKey

        val keyGenerator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            ANDROID_KEYSTORE
        )
        val spec = KeyGenParameterSpec.Builder(
            KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setRandomizedEncryptionRequired(true)
            .build()

        keyGenerator.init(spec)
        return keyGenerator.generateKey()
    }

    fun encrypt(plainText: String): String {
        if (plainText.isEmpty()) return ""
        return runCatching {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, getOrCreateSecretKey())
            val iv = cipher.iv
            val cipherBytes = cipher.doFinal(plainText.toByteArray(StandardCharsets.UTF_8))
            val ivB64 = Base64.encodeToString(iv, Base64.NO_WRAP)
            val ctB64 = Base64.encodeToString(cipherBytes, Base64.NO_WRAP)
            "$VERSION_PREFIX$ivB64:$ctB64"
        }.getOrDefault("")
    }

    fun decrypt(encoded: String?): String {
        if (encoded.isNullOrBlank()) return ""
        if (!encoded.startsWith(VERSION_PREFIX)) {
            // Reject unencrypted legacy plaintext tokens to enforce strict encryption at rest
            return ""
        }
        return runCatching {
            val payload = encoded.removePrefix(VERSION_PREFIX)
            val sepIdx = payload.indexOf(':')
            if (sepIdx <= 0) return ""
            val iv = Base64.decode(payload.substring(0, sepIdx), Base64.NO_WRAP)
            val cipherBytes = Base64.decode(payload.substring(sepIdx + 1), Base64.NO_WRAP)
            val cipher = Cipher.getInstance(TRANSFORMATION)
            val spec = GCMParameterSpec(GCM_TAG_BITS, iv)
            cipher.init(Cipher.DECRYPT_MODE, getOrCreateSecretKey(), spec)
            String(cipher.doFinal(cipherBytes), StandardCharsets.UTF_8)
        }.getOrDefault("")
    }
}
